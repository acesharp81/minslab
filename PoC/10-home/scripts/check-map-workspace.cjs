/* Always-on 3D supply map: layout, navigation, data provenance and responsive controls. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=process.env.HOME_CHECK_URL||'http://127.0.0.1:18100/poc/home/';
const artifact=process.env.HOME_CHECK_ARTIFACTS||'/tmp/home-map-workspace';
fs.mkdirSync(artifact,{recursive:true});
const ready=async page=>{
  await page.goto(root);
  await page.locator('#housing-map-3d canvas').waitFor({state:'visible',timeout:60000});
  await page.locator('.map-scene-block').first().waitFor({state:'visible',timeout:60000});
};
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.HOME_CHECK_CHROME||undefined,args:['--no-sandbox']});
  const errors=[];
  try{
    const page=await browser.newPage({viewport:{width:1600,height:1000}});
    page.on('pageerror',error=>errors.push(error.message));
    await ready(page);
    const scene=await page.locator('#housing-map-3d').boundingBox();
    const panel=await page.locator('.map-side-panel').boundingBox();
    assert(scene&&panel&&scene.x>=panel.x+panel.width-2,'3D map must sit to the right of supply panel');
    assert(scene.width>=1100&&scene.height>=700,'3D map must dominate desktop view');
    assert.equal(await page.locator('#housing-map-3d canvas').count(),1);
    assert.equal(await page.locator('#map-3d-toggle').isVisible(),false,'no 2D/3D mode switch');
    assert.match(await page.locator('#map-3d-status').textContent(),/가상 배치·높이|주변 기존 건물/);
    assert.match(await page.locator('#map-3d-evidence').textContent(),/공식 계획값이 아닙니다/);
    assert.equal(await page.evaluate(()=>MapThreeD.modelStats().simulated),true);
    assert(await page.evaluate(()=>MapThreeD.modelStats().features)>0);
    assert.deepEqual(await page.evaluate(()=>[500,1000,1500].map(n=>BlockMonitor.barHeightFor({target_units:n}))),[33,65,98]);
    assert.equal(await page.locator('#map-3d-block-picker').inputValue(),await page.evaluate(()=>MapThreeD.currentBlock()));
    const data=await (await page.request.get(new URL('api/map/dashboard?measure=SUPPLY',root).href)).json();
    const precise=data.blocks.filter(row=>row.coordinate_basis==='LH_PUBLIC_BLOCK_LABEL_POINT');
    assert.equal(precise.length,66);
    assert((await page.locator('#map-3d-block-picker option').count())>=data.blocks.length);
    assert.equal(await page.locator('.map-scene-block').count(),precise.length);
    await page.screenshot({path:path.join(artifact,'always-3d-desktop.png')});
    await page.locator('#sidebar-toggle').click();
    assert.equal(await page.locator('#sidebar-toggle').getAttribute('aria-expanded'),'true');
    assert((await page.locator('.sidebar').boundingBox()).width>=200);
    assert.equal(await page.locator('#housing-map-3d canvas').count(),1);
    await page.locator('#sidebar-toggle').click();
    assert.equal(await page.locator('#sidebar-toggle').getAttribute('aria-expanded'),'false');
    await page.locator('#map-panel-toggle').click();
    assert.equal(await page.locator('#map-panel-toggle').getAttribute('aria-expanded'),'false');
    assert((await page.locator('.map-side-panel').boundingBox()).width<=50);
    assert.equal(await page.locator('#housing-map-3d canvas').count(),1);
    await page.locator('#map-panel-toggle').click();
    assert.equal(await page.locator('#map-panel-toggle').getAttribute('aria-expanded'),'true');
    await page.locator('[data-map-3d-camera="top"]').click();
    assert.equal(await page.locator('[data-map-3d-camera="top"]').getAttribute('aria-pressed'),'true');
    await page.locator('[data-map-3d-camera="oblique"]').click();
    const policyTab=page.locator('[data-monitor-policy="POL_2025_0907"]');
    await policyTab.click();
    assert.equal(await policyTab.getAttribute('aria-selected'),'true');
    assert.equal(await page.locator('#housing-map-3d canvas').count(),1);
    await page.locator('[data-monitor-policy=""]').click();
    await page.evaluate(()=>MapThreeD.setLevel('municipality'));
    await page.locator('.map-scene-municipality svg').first().waitFor({state:'visible'});
    const maxPie=await page.locator('.map-scene-municipality svg').evaluateAll(nodes=>Math.max(...nodes.map(node=>Number(node.getAttribute('width')))));
    assert.equal(maxPie,92,'largest municipality circle is 1.5 times the prior 61px diameter');
    await page.evaluate(()=>MapThreeD.setLevel('block'));
    await page.locator('.map-scene-block').first().waitFor({state:'visible'});
    const picker=page.locator('#map-3d-block-picker');
    const a4=precise.find(row=>row.district_name.includes('고양창릉')&&row.block==='A4');
    const s1=precise.find(row=>row.district_name.includes('고양창릉')&&row.block==='S1');
    assert(a4&&s1&&a4.latitude!==s1.latitude&&a4.longitude!==s1.longitude);
    await picker.selectOption(s1.id);
    assert.equal(await page.evaluate(()=>MapThreeD.currentBlock()),s1.id);
    await page.locator('#housing-map-3d canvas').waitFor({state:'visible'});
    await page.locator('[data-map-year="2027"]').click();
    await page.locator('#housing-map-3d canvas').waitFor({state:'visible'});
    await page.reload();await ready(page);
    assert.equal(await page.locator('#sidebar-toggle').getAttribute('aria-expanded'),'false');
    assert.equal(await page.locator('#map-panel-toggle').getAttribute('aria-expanded'),'true');
    await page.setViewportSize({width:2560,height:1000});
    const wideScene=await page.locator('#housing-map-3d').boundingBox();
    assert(wideScene.width>=2100,'3D scene must fill ultrawide viewport');
    assert.equal(Math.round(wideScene.x+wideScene.width),2560,'scene must reach right edge');
    assert.equal(await page.locator('#housing-map-3d canvas').count(),1);
    await page.screenshot({path:path.join(artifact,'always-3d-wide.png')});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.locator('#housing-map-3d canvas').count(),1);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1),false);
    await page.locator('#map-panel-toggle').click();
    assert.equal(await page.locator('#map-panel-toggle').getAttribute('aria-expanded'),'true');
    await page.screenshot({path:path.join(artifact,'always-3d-mobile.png')});
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({status:'PASS',preciseBlocks:precise.length,modelFeatures:await page.evaluate(()=>MapThreeD.modelStats().features),desktopScene:scene.width,wideScene:wideScene.width,artifact}));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
