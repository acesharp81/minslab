grant select, insert, update, delete on public.poc08_attachments to service_role;
grant select, insert, update, delete on public.poc08_analysis_runs to service_role;
grant select, insert, update, delete on public.poc08_notice_decisions to service_role;
grant select, insert, update, delete on public.poc08_action_items to service_role;
