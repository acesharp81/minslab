revoke all on public.poc08_attachments from anon, authenticated;
revoke all on public.poc08_analysis_runs from anon, authenticated;
revoke all on public.poc08_notice_decisions from anon, authenticated;
revoke all on public.poc08_action_items from anon, authenticated;
revoke all on public.poc08_pipeline_runs from anon, authenticated;
revoke all on public.poc08_audit_logs from anon, authenticated;

